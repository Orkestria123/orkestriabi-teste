-- ============================================================
-- AJUSTE 12 — O plano de contas do escritório vira a estrutura
--
-- Três coisas, todas derivadas do arquivo "Plano de Contas.csv"
-- exportado do sistema contábil:
--
--  1. `plano_padrao_referencia`: as 1.143 contas ESTRUTURAIS do plano
--     (o export tem 135.739 linhas, mas 134.613 delas são
--     clientes/fornecedores pendurados em 4 classificações — esses
--     entram pelo diário, não por migration).
--
--  2. `estrutura_padrao`: classificação -> papel. É o que substitui os
--     marcos. Mesmo padrão do `dfc_padrao`: uma tabela de referência
--     que o BI lê, em vez de um flag espalhado conta a conta.
--
--  3. Os acumuladores da DRE deixam de ser inventados pelo BI: eles já
--     existem no plano como contas `.98`/`.99` sem filhos
--     (3.01.99 = RECEITA LÍQUIDA, 3.05.99 = LUCRO/PREJUÍZO BRUTO,
--     3.10.99 = RESULTADO OPERACIONAL, 3.99 = RESULTADO LÍQUIDO).
--     O BI passa a calculá-los e exibi-los na posição em que o próprio
--     plano os coloca.
-- ============================================================

-- ------------------------------------------------------------
-- 1) Referência: o plano padrão do escritório
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.plano_padrao_referencia (
  codigo text PRIMARY KEY,
  classificacao text NOT NULL,
  descricao text NOT NULL,
  tipo text NOT NULL,
  natureza text NOT NULL CHECK (natureza IN ('S','A')),
  nivel int NOT NULL,
  conta_pai_classificacao text
);
CREATE INDEX IF NOT EXISTS plano_padrao_referencia_classif
  ON public.plano_padrao_referencia (classificacao);

GRANT SELECT ON public.plano_padrao_referencia TO authenticated;
GRANT ALL ON public.plano_padrao_referencia TO service_role;
ALTER TABLE public.plano_padrao_referencia ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "referencia leitura" ON public.plano_padrao_referencia;
CREATE POLICY "referencia leitura" ON public.plano_padrao_referencia
  FOR SELECT TO authenticated USING (true);

COMMENT ON TABLE public.plano_padrao_referencia IS
  'Plano de contas padrão do escritório (estrutura, sem participantes). '
  'Origem: export do sistema contábil. Participantes entram pelo diário.';

