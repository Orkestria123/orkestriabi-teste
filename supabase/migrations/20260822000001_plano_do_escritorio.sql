  classificacao text NOT NULL,
  papel text NOT NULL,
  demonstracao text CHECK (demonstracao IN ('DRE','BP_ATIVO','BP_PASSIVO')),
  tipo_linha text NOT NULL CHECK (tipo_linha IN ('detalhe','bloco','corrido','tag')),
  rotulo text,
  ordem int NOT NULL DEFAULT 0,
  PRIMARY KEY (classificacao, papel)
);

