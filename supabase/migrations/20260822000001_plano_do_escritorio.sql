DROP INDEX IF EXISTS public.idx_plano_contas_pai;

-- ------------------------------------------------------------
-- 5) Aplica nos escritórios que já existem
-- ------------------------------------------------------------
DO $seed$
DECLARE r record; _res jsonb;
BEGIN
  FOR r IN SELECT id FROM public.tenants LOOP
    WITH ins AS (
      INSERT INTO public.plano_contas
        (tenant_id, company_id, codigo, classificacao, descricao, tipo, natureza,
         nivel, is_sintetica, is_participante, conta_pai_classificacao, ativo)
      SELECT r.id, NULL, pr.codigo, pr.classificacao, pr.descricao, pr.tipo, pr.natureza,
             pr.nivel, (pr.natureza = 'S'), false, pr.conta_pai_classificacao, true
        FROM public.plano_padrao_referencia pr
      ON CONFLICT (tenant_id, COALESCE(company_id, '00000000-0000-0000-0000-000000000000'::uuid), codigo) DO UPDATE
        SET classificacao = EXCLUDED.classificacao,
            descricao     = EXCLUDED.descricao,
            tipo          = EXCLUDED.tipo,
            natureza      = EXCLUDED.natureza,
            nivel         = EXCLUDED.nivel,
            is_sintetica  = EXCLUDED.is_sintetica,
            conta_pai_classificacao = EXCLUDED.conta_pai_classificacao
      RETURNING 1
    )
    SELECT to_jsonb(count(*)) INTO _res FROM ins;
  END LOOP;

  -- vincula a DFC em tudo que ficou sem código
  UPDATE public.plano_contas p
     SET dfc_codigo = (SELECT d.codigo_dfc FROM public.dfc_padrao d
                        WHERE p.classificacao = d.classificacao
                           OR left(p.classificacao, length(d.classificacao) + 1) = d.classificacao || '.'
                        ORDER BY length(d.classificacao) DESC LIMIT 1)
   WHERE p.dfc_codigo IS NULL;

  RAISE NOTICE 'Plano padrão semeado em % escritório(s)', (SELECT count(*) FROM public.tenants);
END;
$seed$;

-- ------------------------------------------------------------
-- 6) DFC: o código `D` (não-caixa) precisa marcar `dfc_nao_caixa`
--
-- O trigger do ajuste 11 derivava só os 4 blocos do método indireto e
-- deixava `dfc_atividade` NULL para os códigos fora deles. A depreciação
-- acumulada ficava então sem bloco E sem flag de não-caixa: não era
-- estornada no operacional e a DFC não fechava (a diferença era
-- exatamente a depreciação do período).
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sincronizar_dfc_atividade()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE _bloco text;
BEGIN
  IF NEW.dfc_codigo IS NULL THEN
    RETURN NEW;
  END IF;
  SELECT bloco INTO _bloco FROM public.dfc_catalogo WHERE codigo = NEW.dfc_codigo;
  IF _bloco IN ('caixa','operacional','investimento','financiamento') THEN
    NEW.dfc_atividade := _bloco;
    NEW.dfc_nao_caixa := false;
  ELSIF _bloco = 'nao_caixa' THEN
    NEW.dfc_atividade := NULL;
    NEW.dfc_nao_caixa := true;
  ELSE                      -- 'resultado' e o que vier depois
    NEW.dfc_atividade := NULL;
    NEW.dfc_nao_caixa := false;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sincronizar_dfc ON public.plano_contas;
CREATE TRIGGER trg_sincronizar_dfc
  BEFORE INSERT OR UPDATE OF dfc_codigo ON public.plano_contas
  FOR EACH ROW EXECUTE FUNCTION public.sincronizar_dfc_atividade();

UPDATE public.plano_contas p
