-- 2) `estrutura_padrao` — classificação -> papel
--
-- Substitui os marcos. Três tipos de linha:
--
--   detalhe  linha comum da demonstração (soma as contas abaixo dela)
--   bloco    acumulador que fecha o próprio bloco  (3.02.99 = total de 3.02)
--   corrido  acumulador do resultado até ali       (3.05.99 = lucro bruto)
--   tag      não é linha; só marca a conta para um indicador (depreciação)
--
-- O `papel` é o nome estável que os indicadores procuram. Antes eles
-- procuravam pelo RÓTULO ("(=) Lucro Bruto"), e por isso quebravam
-- sempre que o rótulo mudava. Agora o rótulo vem do plano e o papel é
-- que é contrato.
-- ------------------------------------------------------------
