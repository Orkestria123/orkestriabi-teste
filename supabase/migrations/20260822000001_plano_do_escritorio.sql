  FROM public.dfc_catalogo d
 WHERE d.codigo = p.dfc_codigo AND d.bloco = 'nao_caixa'
   AND p.dfc_nao_caixa IS DISTINCT FROM true;

-- ------------------------------------------------------------
-- 7) Indicadores padrão, criados e vinculados à estrutura
--
-- As fórmulas referenciam PAPÉIS (`linha`), não contas nem rótulos:
-- "ATIVO_CIRCULANTE / PASSIVO_CIRCULANTE". Quem resolve papel →
-- classificação é o `estrutura_padrao`, então o mesmo indicador serve
-- qualquer empresa do escritório sem reconfiguração conta a conta.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public._termo(_linha text) RETURNS jsonb
LANGUAGE sql IMMUTABLE AS $$
  SELECT jsonb_build_object('tipo','termo','origem','demonstracao','linha',_linha)
$$;
CREATE OR REPLACE FUNCTION public._op(_v text) RETURNS jsonb
LANGUAGE sql IMMUTABLE AS $$ SELECT jsonb_build_object('tipo','operador','valor',_v) $$;
CREATE OR REPLACE FUNCTION public._par(_v text) RETURNS jsonb
LANGUAGE sql IMMUTABLE AS $$ SELECT jsonb_build_object('tipo','parentese','valor',_v) $$;
CREATE OR REPLACE FUNCTION public._num(_v numeric) RETURNS jsonb
LANGUAGE sql IMMUTABLE AS $$ SELECT jsonb_build_object('tipo','constante','valor',_v) $$;

CREATE OR REPLACE FUNCTION public.semear_indicadores_padrao(
  _company_id uuid,
  _substituir boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE _tenant uuid; _n int := 0;
BEGIN
  SELECT tenant_id INTO _tenant FROM public.companies WHERE id = _company_id;
  IF _tenant IS NULL THEN RAISE EXCEPTION 'Empresa não encontrada'; END IF;
  IF NOT (public.is_orkestria_admin() OR public.get_my_tenant_id() = _tenant) THEN
    RAISE EXCEPTION 'Sem permissão';
  END IF;

  IF _substituir THEN
    DELETE FROM public.indicadores_empresa
     WHERE company_id = _company_id AND is_padrao = true;
  END IF;

  WITH def(nome, categoria, modo, descricao, ordem, expressao) AS (VALUES
    ('Liquidez Corrente','Liquidez','numero',
     'Ativo Circulante / Passivo Circulante', 10,
     jsonb_build_array(_termo('ATIVO_CIRCULANTE'), _op('/'), _termo('PASSIVO_CIRCULANTE'))),
    ('Liquidez Seca','Liquidez','numero',
     '(Ativo Circulante − Estoques) / Passivo Circulante', 20,
     jsonb_build_array(_par('('), _termo('ATIVO_CIRCULANTE'), _op('-'), _termo('ESTOQUES'), _par(')'),
                       _op('/'), _termo('PASSIVO_CIRCULANTE'))),
    ('Liquidez Imediata','Liquidez','numero',
     'Disponível / Passivo Circulante', 30,
     jsonb_build_array(_termo('DISPONIVEL'), _op('/'), _termo('PASSIVO_CIRCULANTE'))),
    ('Liquidez Geral','Liquidez','numero',
     '(AC + Realizavel LP) / (PC + PNC)', 40,
     jsonb_build_array(_par('('), _termo('ATIVO_CIRCULANTE'), _op('+'), _termo('REALIZAVEL_LP'), _par(')'),
                       _op('/'),
                       _par('('), _termo('PASSIVO_CIRCULANTE'), _op('+'), _termo('PASSIVO_NAO_CIRCULANTE'), _par(')'))),
    ('Endividamento Geral','Estrutura','percentual',
     '(PC + PNC) / Ativo Total × 100', 50,
     jsonb_build_array(_par('('), _termo('PASSIVO_CIRCULANTE'), _op('+'), _termo('PASSIVO_NAO_CIRCULANTE'), _par(')'),
                       _op('/'), _termo('ATIVO_TOTAL'), _op('*'), _num(100))),
    ('Composição do Endividamento','Estrutura','percentual',
     'PC / (PC + PNC) × 100', 60,
     jsonb_build_array(_termo('PASSIVO_CIRCULANTE'), _op('/'),
                       _par('('), _termo('PASSIVO_CIRCULANTE'), _op('+'), _termo('PASSIVO_NAO_CIRCULANTE'), _par(')'),
                       _op('*'), _num(100))),
    ('Imobilização do PL','Estrutura','percentual',
     'Imobilizado / Patrimônio Líquido × 100', 70,
     jsonb_build_array(_termo('IMOBILIZADO'), _op('/'), _termo('PATRIMONIO_LIQUIDO'), _op('*'), _num(100))),
    ('Dívida Líquida / EBITDA','Estrutura','numero',
     '(Empréstimos − Disponível) / EBITDA', 80,
     jsonb_build_array(_par('('), _termo('EMPRESTIMOS'), _op('-'), _termo('DISPONIVEL'), _par(')'),
                       _op('/'), _termo('EBITDA'))),
    ('Margem Bruta','Rentabilidade','percentual',
     'Lucro Bruto / Receita Líquida × 100', 90,
     jsonb_build_array(_termo('LUCRO_BRUTO'), _op('/'), _termo('RECEITA_LIQUIDA'), _op('*'), _num(100))),
    ('Margem Líquida','Rentabilidade','percentual',
     'Lucro Líquido / Receita Líquida × 100', 100,
     jsonb_build_array(_termo('LUCRO_LIQUIDO'), _op('/'), _termo('RECEITA_LIQUIDA'), _op('*'), _num(100))),
    ('Margem EBITDA','Rentabilidade','percentual',
     'EBITDA / Receita Líquida × 100', 110,
     jsonb_build_array(_termo('EBITDA'), _op('/'), _termo('RECEITA_LIQUIDA'), _op('*'), _num(100))),
    ('Margem Operacional','Rentabilidade','percentual',
     'EBIT / Receita Líquida × 100', 115,
     jsonb_build_array(_termo('EBIT'), _op('/'), _termo('RECEITA_LIQUIDA'), _op('*'), _num(100))),
    ('ROA','Rentabilidade','percentual',
     'Lucro Líquido / Ativo Total × 100', 120,
     jsonb_build_array(_termo('LUCRO_LIQUIDO'), _op('/'), _termo('ATIVO_TOTAL'), _op('*'), _num(100))),
    ('ROE','Rentabilidade','percentual',
     'Lucro Líquido / Patrimônio Líquido × 100', 130,
     jsonb_build_array(_termo('LUCRO_LIQUIDO'), _op('/'), _termo('PATRIMONIO_LIQUIDO'), _op('*'), _num(100))),
    ('Giro do Ativo','Atividade','numero',
     'Receita Líquida / Ativo Total', 140,
     jsonb_build_array(_termo('RECEITA_LIQUIDA'), _op('/'), _termo('ATIVO_TOTAL'))),
    ('Prazo Médio de Recebimento','Atividade','numero',
     '(Contas a Receber / Receita Bruta) × 30', 150,
     jsonb_build_array(_par('('), _termo('CONTAS_A_RECEBER'), _op('/'), _termo('RECEITA_BRUTA'), _par(')'),
                       _op('*'), _num(30))),
    -- Custos vêm NEGATIVOS na convenção da DRE (receita +, custo −); por
    -- isso o divisor é (0 − Custos), senão o prazo sairia negativo.
    ('Prazo Médio de Pagamento','Atividade','numero',
     '(Fornecedores / Custos) × 30', 160,
     jsonb_build_array(_par('('), _termo('FORNECEDORES'), _op('/'),
                       _par('('), _num(0), _op('-'), _termo('CUSTOS'), _par(')'), _par(')'),
                       _op('*'), _num(30)))
  ),
  ins AS (
    INSERT INTO public.indicadores_empresa
      (tenant_id, company_id, nome, categoria, formula, modo_analise,
       descricao, visibilidade, is_padrao, ordem)
    SELECT _tenant, _company_id, d.nome, d.categoria,
           jsonb_build_object('expressao', d.expressao), d.modo,
           d.descricao, 'indicadores', true, d.ordem
      FROM def d
     WHERE NOT EXISTS (
       SELECT 1 FROM public.indicadores_empresa e
        WHERE e.company_id = _company_id AND e.nome = d.nome
     )
    RETURNING 1
  )
  SELECT count(*) INTO _n FROM ins;

  RETURN jsonb_build_object('indicadores_criados', _n);
END;
$fn$;

