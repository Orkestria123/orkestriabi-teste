-- ------------------------------------------------------------
-- 8) `plano_padrao_resumo` sem a métrica de marcos
--
-- A coluna `marco` acabou de ser dropada; o resumo contava ela. No lugar,
-- conta os acumuladores que o plano declara (.98/.99) — que é o número
-- equivalente e agora vem do próprio plano.
-- ------------------------------------------------------------
DO $ajuste$
DECLARE _def text;
BEGIN
  SELECT pg_get_functiondef(oid) INTO _def FROM pg_proc
   WHERE proname = 'plano_padrao_resumo' AND pronamespace = 'public'::regnamespace
   LIMIT 1;
  IF _def IS NULL THEN RETURN; END IF;
  _def := replace(_def,
    'count(*) FILTER (WHERE marco IS NOT NULL)',
    'count(*) FILTER (WHERE is_sintetica AND classificacao ~ ''[.](98|99)([.]|$)'')');
  _def := replace(_def, '''marcos'', _marcos', '''acumuladores'', _marcos, ''marcos'', _marcos');
  EXECUTE _def;
END;
$ajuste$;
