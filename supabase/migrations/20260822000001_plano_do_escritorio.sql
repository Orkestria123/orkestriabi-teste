-- ------------------------------------------------------------
-- 3) Semear o plano padrão de um escritório
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.semear_plano_padrao(
  _tenant_id uuid,
  _substituir boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE _ins int := 0; _upd int := 0; _dfc jsonb;
BEGIN
  IF NOT (public.is_orkestria_admin() OR public.get_my_tenant_id() = _tenant_id) THEN
    RAISE EXCEPTION 'Sem permissão';
  END IF;

  IF _substituir THEN
    DELETE FROM public.plano_contas
     WHERE tenant_id = _tenant_id AND company_id IS NULL AND is_participante = false;
  END IF;

  WITH ins AS (
    INSERT INTO public.plano_contas
      (tenant_id, company_id, codigo, classificacao, descricao, tipo, natureza,
       nivel, is_sintetica, is_participante, conta_pai_classificacao, ativo)
    SELECT _tenant_id, NULL, r.codigo, r.classificacao, r.descricao, r.tipo, r.natureza,
           r.nivel, (r.natureza = 'S'), false, r.conta_pai_classificacao, true
      FROM public.plano_padrao_referencia r
    ON CONFLICT (tenant_id, COALESCE(company_id, '00000000-0000-0000-0000-000000000000'::uuid), codigo) DO UPDATE
      SET classificacao = EXCLUDED.classificacao,
          descricao     = EXCLUDED.descricao,
          tipo          = EXCLUDED.tipo,
          natureza      = EXCLUDED.natureza,
          nivel         = EXCLUDED.nivel,
          is_sintetica  = EXCLUDED.is_sintetica,
          conta_pai_classificacao = EXCLUDED.conta_pai_classificacao,
          updated_at    = now()
    RETURNING (xmax = 0) AS inserida
  )
  SELECT count(*) FILTER (WHERE inserida), count(*) FILTER (WHERE NOT inserida)
    INTO _ins, _upd FROM ins;

  -- já vincula a DFC da planilha
  SELECT public.aplicar_dfc_padrao(_tenant_id, NULL, false) INTO _dfc;

  RETURN jsonb_build_object('inseridas', _ins, 'atualizadas', _upd, 'dfc', _dfc);
END;
$fn$;

REVOKE EXECUTE ON FUNCTION public.semear_plano_padrao(uuid, boolean) FROM anon, public;
GRANT EXECUTE ON FUNCTION public.semear_plano_padrao(uuid, boolean) TO authenticated, service_role;

